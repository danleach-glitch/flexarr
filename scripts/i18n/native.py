"""The text the operating systems read themselves (docs/languages.md, *Built in and downloaded*): Apple's App Intents
titles and Siri phrases and each target's Info.plist prompts, and Android's string resources (the app name, widget
and shortcut labels). `collect` adds their English to en.json; `outputs` writes them back out in every language as
String Catalogs and values-<code>/strings.xml, and Android's locales_config.xml. These are what make the App Store
and Google Play list the languages."""
import json
import re
import xml.sax.saxutils as sx
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
APPLE = ROOT / "clients/apple"
PROJECT = APPLE / "project.yml"
# Outside Shared/ (which every target compiles): each file is added to its own target in project.yml.
APPLE_OUT = APPLE / "Languages"
ANDROID_RES = ROOT / "clients/android/app/src/main/res"
HEADER = "Generated by `make strings` from languages/. Don't edit."

LIT = r'"((?:[^"\\\n]|\\.)*)"'
INTENT_PATTERNS = [
    re.compile(r"LocalizedStringResource\s*=\s*" + LIT),
    re.compile(r"IntentDescription\(\s*" + LIT),
    re.compile(r"@Parameter\(\s*title:\s*" + LIT),
    re.compile(r"shortTitle:\s*" + LIT),
    re.compile(r"TypeDisplayRepresentation\(\s*name:\s*" + LIT),
    re.compile(r"DisplayRepresentation\(\s*title:\s*" + LIT),
    re.compile(r"requestValueDialog:\s*" + LIT),
]
PHRASES = re.compile(r"phrases:\s*\[(.*?)\]", re.S)
PLIST_KEY = re.compile(r"^\s+(NS\w+UsageDescription):\s*" + LIT + r"\s*$", re.M)
TARGET = re.compile(r"^  ([A-Za-z][A-Za-z0-9]*):\s*$", re.M)
ANDROID_STRING = re.compile(r'<string name="([a-z0-9_]+)"(?: [^>]*)?>(.*?)</string>', re.S)


def _unescape_swift(s):
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def _phrase(s):
    """A Siri phrase with \\(.applicationName) and \\(\\.$x) as ${applicationName} and ${x}, or None."""
    s = s.replace("\\(.applicationName)", "${applicationName}")
    s = re.sub(r"\\\(\\\.\$([A-Za-z_]\w*)\)", r"${\1}", s)
    return None if "\\(" in s else _unescape_swift(s)


def _swift_files():
    return [p for p in sorted((APPLE / "Shared").rglob("*.swift")) + sorted((APPLE / "FlexarriOS").rglob("*.swift"))
            + sorted((APPLE / "FlexarrTV").rglob("*.swift")) if "/.build/" not in p.as_posix()]


def apple_intents():
    """(intent strings, phrases): the App Intents text Shortcuts and Siri read from the bundle."""
    strings, phrases = set(), set()
    for path in _swift_files():
        src = path.read_text(encoding="utf-8")
        if "AppIntent" not in src and "AppEntity" not in src and "AppEnum" not in src and "AppShortcut" not in src:
            continue
        for pat in INTENT_PATTERNS:
            for m in pat.finditer(src):
                if "\\(" not in m.group(1):
                    strings.add(_unescape_swift(m.group(1)))
        for block in PHRASES.finditer(src):
            for lit in re.finditer(LIT, block.group(1)):
                p = _phrase(lit.group(1))
                if p:
                    phrases.add(p)
    return strings, phrases


def plist_prompts():
    """{target: {plist key: English}} from project.yml's Info.plist properties."""
    text = PROJECT.read_text(encoding="utf-8")
    targets_at = text.index("\ntargets:")
    starts = [(m.start(), m.group(1)) for m in TARGET.finditer(text, targets_at)]
    out = {}
    for i, (start, name) in enumerate(starts):
        end = starts[i + 1][0] if i + 1 < len(starts) else len(text)
        for m in PLIST_KEY.finditer(text, start, end):
            out.setdefault(name, {})[m.group(1)] = _unescape_swift(m.group(2))
    return out


def _android_unescape(s):
    s = sx.unescape(s.strip())
    return s.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n")


def android_strings():
    """{resource name: English} from the app's values/*.xml."""
    out = {}
    for path in sorted((ANDROID_RES / "values").glob("*.xml")):
        for m in ANDROID_STRING.finditer(path.read_text(encoding="utf-8")):
            if 'translatable="false"' in m.group(0):
                continue
            out[m.group(1)] = _android_unescape(m.group(2))
    return out


def collect():
    """{English: scopes} the operating systems read, to add to en.json. Their English becomes the key, so Apple's
    ${x} placeholders read as ICU values {x} with a $ before them."""
    found = {}
    intents, phrases = apple_intents()
    for s in intents | phrases:
        found.setdefault(s, set()).add("apple")
    for prompts in plist_prompts().values():
        for s in prompts.values():
            found.setdefault(s, set()).add("apple")
    for s in android_strings().values():
        found.setdefault(s, set()).add("android")
    return found


def _catalog(keys, built, value=lambda k: k):
    strings = {}
    for key in sorted(keys):
        loc = {}
        for code, live in sorted(built.items()):
            if value(key) in live:
                loc[code] = {"stringUnit": {"state": "translated", "value": live[value(key)]}}
        entry = {"extractionState": "manual"}
        if loc:
            entry["localizations"] = loc
        strings[key] = entry
    return json.dumps({"sourceLanguage": "en", "strings": strings, "version": "1.0"}, ensure_ascii=False,
                      indent=2, sort_keys=True) + "\n"


def _android_qualifier(code):
    parts = code.split("-")
    return f"values-{code}" if len(parts) == 1 else "values-b+" + "+".join(parts)


def _android_escape(s):
    s = sx.escape(s).replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    return "\\" + s if s[:1] in "@?" else s


def outputs(found, built, registry):
    out = {}
    intents, phrases = apple_intents()
    out[APPLE_OUT / "Localizable.xcstrings"] = _catalog(intents, built)
    out[APPLE_OUT / "AppShortcuts.xcstrings"] = _catalog(phrases, built)
    for target, prompts in sorted(plist_prompts().items()):
        out[APPLE_OUT / target / "InfoPlist.xcstrings"] = _catalog(prompts.keys(), built, value=lambda k, p=prompts: p[k])

    names = android_strings()
    for code, live in sorted(built.items()):
        rows = [(n, live[e]) for n, e in sorted(names.items()) if e in live]
        if not rows:
            continue
        body = "\n".join(f'    <string name="{n}">{_android_escape(v)}</string>' for n, v in rows)
        out[ANDROID_RES / _android_qualifier(code) / "strings.xml"] = (
            f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n<resources>\n{body}\n</resources>\n')
    locales = ["en"] + sorted(c for c in built if c != "en")
    body = "\n".join(f'    <locale android:name="{c}" />' for c in locales)
    out[ANDROID_RES / "xml" / "locales_config.xml"] = (
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {HEADER} -->\n'
        f'<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n{body}\n</locale-config>\n')
    return out
