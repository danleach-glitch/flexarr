"""Flexarr's shared words (languages/words.json) as constants on every platform: Words.play in TypeScript, Swift and
Kotlin, Words.Play in C#. Each constant's value is the word's key in en.json, so `t(Words.play)` looks it up like
`t("Play")` would, and changing the word in words.json changes it everywhere."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "languages" / "words.json"
TS = ROOT / "frontend/src/i18n/words.generated.ts"
SWIFT = ROOT / "clients/apple/FlexarrKit/Sources/FlexarrKit/Localization/Words.generated.swift"
KOTLIN = ROOT / "clients/android/core/src/main/kotlin/io/github/flexarr/core/i18n/Words.kt"
CS = ROOT / "src/Flexarr.Core/Localization/Words.generated.cs"
HEADER = "Generated from languages/words.json by `make strings`. Don't edit; change the word there."
NAME = re.compile(r"^[a-z][A-Za-z0-9]*$")


def load(path=SOURCE):
    """{name: key}."""
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))["words"]


def validate(words):
    problems = []
    seen = {}
    for name, key in words.items():
        if not NAME.match(name):
            problems.append(f"words.json: {name!r} isn't camelCase")
        if key in seen:
            problems.append(f"words.json: {name} and {seen[key]} are the same word")
        seen[key] = name
    return problems


def by_name(words, name):
    """The key for a name as code writes it (C# capitalises the first letter)."""
    return words.get(name) or words.get(name[:1].lower() + name[1:])


def _str(s, quote='"'):
    return quote + s.replace("\\", "\\\\").replace(quote, "\\" + quote).replace("\n", "\\n") + quote


def outputs(words):
    names = sorted(words)
    ts = [f"// {HEADER}", "", "export const Words = {"] + [f"  {n}: {_str(words[n], chr(39))}," for n in names] + ["} as const", ""]
    swift = [f"// {HEADER}", "", "/// Flexarr's shared words: `t(Words.play)`.", "public enum Words {"]
    swift += [f"    public static let {n} = {_str(words[n])}" for n in names] + ["}", ""]
    kotlin = [f"// {HEADER}", "", "package io.github.flexarr.core.i18n", "", "/** Flexarr's shared words: `t(Words.play)`. */",
              "@Suppress(\"ktlint\")", "object Words {"]
    kotlin += [f"    const val {n} = {_str(words[n]).replace('$', chr(92) + '$')}" for n in names] + ["}", ""]
    cs = [f"// {HEADER}", "", "// <auto-generated />", "namespace Flexarr.Core.Localization;", "",
          "/// <summary>Flexarr's shared words: <c>Loc.T(Words.Play)</c>.</summary>", "public static class Words", "{"]
    cs += [f"    public const string {n[:1].upper() + n[1:]} = {_str(words[n])};" for n in names] + ["}", ""]
    return {TS: "\n".join(ts), SWIFT: "\n".join(swift), KOTLIN: "\n".join(kotlin), CS: "\n".join(cs)}
